function formatFundSize(size: number): string {
  if (size >= 1e9) return `${(size / 1e9).toFixed(1)}B`;
  if (size >= 1e6) return `${(size / 1e6).toFixed(0)}M`;
  return `${size.toLocaleString()}`;
}

function computeCumulativeGrowth(returns: MonthlyReturn[]): { date: string; value: number }[] {
  const result: { date: string; value: number }[] = [];
  let cumValue = 10000;
  if (returns.length > 0) {
    const firstDate = new Date(returns[0].date);
    firstDate.setMonth(firstDate.getMonth() - 1);
    result.push({ date: firstDate.toISOString().slice(0, 10), value: 10000 });
  }
  for (const r of returns) {
    cumValue *= 1 + r.value / 100;
    result.push({ date: r.date, value: Math.round(cumValue * 100) / 100 });
  }
  return result;
}

export function getCumulativeGrowth(fund: Fund) {
  return computeCumulativeGrowth(fund.monthlyReturns);
}

export function getBenchmarkCumulativeGrowth(fund: Fund) {
  return computeCumulativeGrowth(fund.benchmarkReturns);
}

export function getAlignedCumulativeGrowth(fund: Fund) {
  const fundReturns = fund.monthlyReturns;
  const benchReturns = fund.benchmarkReturns;
  if (!benchReturns || benchReturns.length === 0) return { fund: getCumulativeGrowth(fund), benchmark: [] };
  const benchDates = new Set(benchReturns.map(r => r.date.slice(0, 7)));
  const alignedFund = fundReturns.filter(r => benchDates.has(r.date.slice(0, 7)));
  const fundDates = new Set(alignedFund.map(r => r.date.slice(0, 7)));
  const alignedBench = benchReturns.filter(r => fundDates.has(r.date.slice(0, 7)));
  return {
    fund: computeCumulativeGrowth(alignedFund),
    benchmark: computeCumulativeGrowth(alignedBench),
  };
}

export function getFundById(id: string): Fund | undefined {
  return funds.find(f => f.id === id);
}

